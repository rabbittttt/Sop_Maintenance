import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../web/app.js',import.meta.url),'utf8');
const context=vm.createContext({localStorage:{getItem:()=>null}});
vm.runInContext(source.split("document.addEventListener('click'")[0],context);
const run=code=>vm.runInContext(code,context);
run(`state={current_month:'2026-11',products:[{id:'p',brand:'智界',model:'R7 2027款',generation:'g',version:'Max'}],sales:[],model_sales:[{generation:'g',month:'2026-01',metric:'locked_orders',value:123}],plans:[],demand_plans:[{brand:'智界',model:'R7 2027款',month:'2026-12',quantity:3000}],months:['2026-12'],plan_end:'2027-12',meta:{}};metric='locked_orders';range='rolling';`);
assert.equal(run("demandQuantity(state.products,'2026-12')"),3000);
assert.equal(run("demandQuantity(state.products,'2026-11')"),null);
assert.doesNotMatch(run("planRow(state.products,'R7','model','g',['2026-12'])"),/metric-demand-row/);
run('showDemand=true');
const row=run("planRow(state.products,'R7','model','g',['2026-12'])");
assert.match(row,/rowspan="3"/);
assert.match(row,/要货计划/);
assert.match(row,/3,000/);
assert.deepEqual([...row.matchAll(/data-plan-metric="([^"]+)"/g)].map(m=>m[1]),['locks','demand','sop']);
run('showLocks=false');
const withoutLocks=run("planRow(state.products,'R7','model','g',['2026-12'])");
assert.deepEqual([...withoutLocks.matchAll(/data-plan-metric="([^"]+)"/g)].map(m=>m[1]),['demand','sop']);
assert.match(withoutLocks.split('</tr>')[0],/class="sticky-name" rowspan="2"/);
assert.equal([...withoutLocks.matchAll(/class="sticky-name"/g)].length,1);
run('showLocks=true');
assert.match(run("calendarPlanCell(state.products,'2026','locks',true)"),/>123</);
run(`state.products=[{id:'s',brand:'享界',model:'X4 2026款',summary_generation:'X4'}];state.generation_members={products:[{id:'a',brand:'享界',model:'S9 2026款',parent_generation:'X4'},{id:'b',brand:'享界',model:'S9T 2026款',parent_generation:'X4'}]};state.demand_plans=[{brand:'享界',model:'S9 2026款',month:'2026-12',quantity:10},{brand:'享界',model:'S9T 2026款',month:'2026-12',quantity:20}];`);
assert.equal(run("demandQuantity(state.products,'2026-12')"),30);
run("state.demand_plans.push({brand:'享界',model:'X4 2026款',month:'2026-12',quantity:0})");
assert.equal(run("demandQuantity(state.products,'2026-12')"),0);
assert.equal(run('viewConfig().showDemand'),true);
console.log('PASS: demand visibility, model matching, blank/zero, parent precedence and annual locks.');
